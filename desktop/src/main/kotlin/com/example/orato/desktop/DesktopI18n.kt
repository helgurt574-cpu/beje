import java.util.prefs.Preferences

enum class DesktopLanguage(
    val code: String,
    val displayName: String,
    val rtl: Boolean
) {
    TURKISH("tr", "Türkçe", false),
    KURMANJI("ku", "Kurmancî", false),
    ARABIC("ar", "العربية", true),
    FARSI("fa", "فارسی", true),
    ENGLISH("en", "English", false);

    companion object {
        fun fromCode(code: String?): DesktopLanguage? = entries.firstOrNull { it.code == code }
    }
}

object DesktopI18n {
    private const val PREF_LANG = "ui_language"

    private val prefs = Preferences.userRoot().node("orato")
    private var currentLanguage: DesktopLanguage = DesktopLanguage.fromCode(prefs.get(PREF_LANG, null))
        ?: DesktopLanguage.fromCode(Locale.getDefault().language)
        ?: DesktopLanguage.TURKISH

    fun language(): DesktopLanguage = currentLanguage

    fun setLanguage(language: DesktopLanguage) {
        currentLanguage = language
        prefs.put(PREF_LANG, language.code)
    }

    fun orientation(): ComponentOrientation =
        if (currentLanguage.rtl) ComponentOrientation.RIGHT_TO_LEFT else ComponentOrientation.LEFT_TO_RIGHT

    fun t(key: String): String =
        translations[currentLanguage]?.get(key) ?: translations.getValue(DesktopLanguage.TURKISH)[key] ?: key

    fun words(count: Int): String = when (currentLanguage) {
        DesktopLanguage.ENGLISH -> if (count == 1) "1 word" else "$count words"
        else -> t("label.words").format(count)
